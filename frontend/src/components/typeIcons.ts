/** The icon for a key; unknown keys get the generic box icon rather than nothing. */
export function typeIcon(key: string): LucideIcon {
  return TYPE_ICONS[key] ?? Box;
}

/** Draws the icon for a registry icon key. */
export function TypeIconGlyph({ icon, ...props }: LucideProps & { icon: string }) {
  // The icons are module-level components picked from a fixed map, not created here.
  return createElement(typeIcon(icon), props);
}
