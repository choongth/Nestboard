const SIDE_POSITION: Record<Side, Position> = { top: Position.Top, right: Position.Right, bottom: Position.Bottom, left: Position.Left };

/** What the editor draws on one canvas at rest, as Canvas.tsx and ConnectionEdge.tsx build it. */
function canvasLayout(diagram: Diagram, canvasId: NodeId) {
  const externals = externalBoxes(diagram, canvasId);
  const rects = new Map<NodeId, { x: number; y: number; width: number; height: number }>();
  for (const n of Object.values(diagram.nodes)) {
    if (n.parentId === canvasId) rects.set(n.id, { ...n.position, width: BOX_WIDTH, height: BOX_HEIGHT });
  }
  for (const e of externals) rects.set(e.id, { ...e.position, width: EXTERNAL_WIDTH, height: EXTERNAL_HEIGHT });

  const { lines, external } = connectionsOn(diagram, canvasId);
  const leaving = external.map((e) => ({
    edgeId: e.edgeId,
    from: e.direction === "out" ? e.inside : e.outside,
    to: e.direction === "out" ? e.outside : e.inside,
    lifted: e.lifted,
    parallel: e.parallel,
  }));
  return {
    canvas: canvasId,
    boxes: [...rects.keys()].filter((id) => diagram.nodes[id]!.parentId === canvasId),
    external: externals.map((e) => ({ id: e.id, x: e.position.x, y: e.position.y, location: location(diagram, e.id) })),
    lines: [...lines, ...leaving].map((line) => {
      const { source, target } = spreadAnchors(facingAnchors(rects.get(line.from)!, rects.get(line.to)!), line.parallel);
      const [path, labelX, labelY] = getBezierPath({
        sourceX: source.x,
        sourceY: source.y,
        sourcePosition: SIDE_POSITION[source.side],
        targetX: target.x,
        targetY: target.y,
        targetPosition: SIDE_POSITION[target.side],
      });
      return { edge: line.edgeId, from: line.from, to: line.to, lifted: line.lifted, source, target, controls: controls(path), label: [labelX, labelY] };
    }),
  };
}

/** externalLocation in Canvas.tsx. */
function location(diagram: Diagram, id: NodeId): string {
  const path = getPath(diagram, id).map((n) => n.title);
  return (path.length > 2 ? path.slice(1) : path).join(" › ");
}

/** The two control points of a path "M x,y C c1x,c1y c2x,c2y x,y". */
function controls(path: string): number[][] {
  const numbers = path.match(/-?[\d.]+(e-?\d+)?/g)!.map(Number);
  if (numbers.length !== 8) throw new Error(`Unexpected path ${path}`);
  return [numbers.slice(2, 4), numbers.slice(4, 6)];
}

function layoutOf(name: string, file: unknown) {
  const parsed = fromFile(file);
  if (!parsed.ok) throw new Error(`${name}: ${parsed.error}`);
  const diagram = parsed.diagram;
  const canvases = Object.values(diagram.nodes).filter((n) => Object.values(diagram.nodes).some((c) => c.parentId === n.id));
  return { name, document: file, canvases: canvases.map((n) => canvasLayout(diagram, n.id)) };
}

