/** A technology's mark as the editor draws it on `background`: one-colour logos with their colour, full-colour ones with their backing. */
function markOn(text: string, background: string) {
  const mark = technologyMark(text);
  if (mark?.kind === "logo") {
    const drawing = drawings.simple[mark.slug]!;
    return { kind: "logo", title: mark.title, path: drawing.path, color: logoColor(drawing, background) };
  }
  if (mark?.kind !== "color") return mark;
  return { ...mark, backing: needsBacking(drawings.color[mark.key]!, background) ? LOGO_BACKING : null };
}

function editorLayout() {
  const examples = ["box-types-gallery.json", "connection-types-gallery.json"].map((name) =>
    layoutOf(name, JSON.parse(readFileSync(new URL(name, EXAMPLES), "utf8"))),
  );
  return {
    comment: "Generated by frontend/src/serverFiles.test.ts from the editor's code. Do not edit.",
    diagrams: [layoutOf("shop", SHOP), ...examples],
    technologies: TECHNOLOGIES.map((text) => ({
      text,
      onBox: markOn(text, BOX_BACKGROUND),
      onNote: markOn(text, NOTE_BACKGROUND),
    })),
    monograms: Object.fromEntries(["HAProxy", "AWS Lambda", "SQS", "x", "数据库 集群", "a-b c", "!!!"].map((t) => [t, monogram(t)])),
  };
}

// ---- The check ----

describe("files for the server's PDF export", () => {
  it.each([
    ["visuals.json", VISUALS, visuals],
    ["editor_layout.json", LAYOUT, editorLayout],
  ] as const)("%s is up to date", (_name, file, make) => {
    const content = JSON.stringify(make(), null, 2) + "\n";
    if (process.env.UPDATE_SERVER_FILES === "1") writeFileSync(file, content, "utf8");
    const written = existsSync(file) ? readFileSync(file, "utf8") : "";
    expect(written, "Out of date: run UPDATE_SERVER_FILES=1 npx vitest run src/serverFiles.test.ts").toBe(content);
  });
});
