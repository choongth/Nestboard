function visuals() {
  // Every theme colour, e.g. "surface-raised": "#242831".
  const colors = Object.fromEntries([...css.matchAll(/--color-([a-z0-9-]+):\s*([^;]+);/g)].map((m) => [m[1]!, m[2]!.trim()]));
  const icons = { ...TYPE_ICONS, layers: Layers };
  return {
    comment: "Generated by frontend/src/serverFiles.test.ts from the editor's code. Do not edit.",
    colors,
    boxTypes: {
      fallback: GENERIC_TYPE_ID,
      categories: Object.fromEntries(boxTypes.categories.map((c) => [c.id, { label: c.label, color: c.color }])),
      types: Object.fromEntries(boxTypes.types.map((t) => [t.id, { label: t.label, category: t.categoryId, icon: t.icon }])),
    },
    edgeTypes: {
      fallback: GENERIC_EDGE_TYPE_ID,
      categories: Object.fromEntries(edgeTypes.categories.map((c) => [c.id, { label: c.label, color: c.color }])),
      types: Object.fromEntries(
        edgeTypes.types.map((t) => [t.id, { label: t.label, verb: t.verb, category: t.categoryId, icon: t.icon, style: t.style }]),
      ),
    },
    lines: lineLook(),
    iconTileTint: ICON_TILE_TINT,
    // lucide icons (24×24, stroked): what goes inside their <svg>.
    icons: Object.fromEntries(Object.entries(icons).map(([key, icon]) => [key, innerSvg(renderToStaticMarkup(createElement(icon)))])),
    // Technology logos with every name they answer to. simple-icons ones (24×24, filled) are
    // coloured to read on a box and on a note; full-colour ones may need a light backing there.
    logos: ALL_LOGOS.map(({ logo, names }) => {
      if (logo.set === "simple") {
        const drawing = drawings.simple[logo.slug]!;
        return {
          set: "simple",
          title: logo.title,
          names,
          path: drawing.path,
          colorOnBox: logoColor(drawing, BOX_BACKGROUND),
          colorOnNote: logoColor(drawing, NOTE_BACKGROUND),
        };
      }
      const drawing = drawings.color[logo.key]!;
      return {
        set: "color",
        title: logo.title,
        key: logo.key,
        names,
        svg: `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${drawing.width} ${drawing.height}">${drawing.body}</svg>`,
        backingOnBox: needsBacking(drawing, BOX_BACKGROUND),
        backingOnNote: needsBacking(drawing, NOTE_BACKGROUND),
      };
    }),
    logoBacking: LOGO_BACKING,
  };
}

/** How lines are drawn, from their rules in index.css. */
function lineLook() {
  const base = cssRule(".react-flow .react-flow__edge-path.nb-connection");
  const strokes: Record<string, { width: number; dash?: number[]; cap?: string }> = {};
  for (const stroke of ["solid", "dashed", "long-dashed", "dotted", "double"] as const) {
    const rule = stroke === "solid" ? {} : cssRule(`.react-flow .react-flow__edge-path.nb-stroke-${stroke}`);
    strokes[stroke] = {
      width: Number(rule["stroke-width"] ?? base["stroke-width"]),
      ...(rule["stroke-dasharray"] && { dash: rule["stroke-dasharray"].split(/\s+/).map(Number) }),
      ...(rule["stroke-linecap"] && { cap: rule["stroke-linecap"] }),
    };
  }
  return {
    strokes,
    doubleCoreWidth: Number(cssRule(".nb-double-core")["stroke-width"]),
    openArrowWidth: Number(cssRule(".nb-marker-open")["stroke-width"]),
    liftedOpacity: Number(cssRule(".react-flow__edge.nb-lifted")["opacity"]),
  };
}

/** The declarations of the rule for exactly `selector` in index.css. */
function cssRule(selector: string): Record<string, string> {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`No rule for ${selector} in index.css`);
  const body = css.slice(css.indexOf("{", start) + 1, css.indexOf("}", start));
  return Object.fromEntries(
    body
      .split(";")
      .map((d) => d.trim())
      .filter(Boolean)
      .map((d) => [d.slice(0, d.indexOf(":")).trim(), d.slice(d.indexOf(":") + 1).trim()]),
  );
}

function innerSvg(markup: string): string {
  const match = markup.match(/^<svg[^>]*>(.*)<\/svg>$/s);
  if (!match) throw new Error(`Not an svg: ${markup}`);
  return match[1]!;
}

