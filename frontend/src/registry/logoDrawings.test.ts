// logoDrawings.json is generated: the drawings of SIMPLE_LOGOS from
// simple-icons and of COLOR_LOGOS from @iconify-json/logos, nothing else.
// This checks it is up to date; to regenerate it after changing either list
// or updating either package:
//   UPDATE_LOGO_DRAWINGS=1 npx vitest run src/registry/logoDrawings.test.ts

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import * as simpleIcons from "simple-icons";
import { describe, expect, it } from "vitest";
import { BOX_BACKGROUND } from "@/canvas/boxStyle";
import { logoColor, needsBacking, type ColorDrawing, type LogoDrawings, type SimpleDrawing } from "./logoDrawings";
import { COLOR_LOGOS, contrastRatio, SIMPLE_LOGOS } from "./technologyLogos";

const FILE = new URL("./logoDrawings.json", import.meta.url);

interface IconSet {
  width?: number;
  height?: number;
  icons: Record<string, { body: string; width?: number; height?: number }>;
}

/** Every colour a drawing paints with; a shape with no fill of its own is painted black. */
function colorsOf(body: string): string[] {
  const colors = new Set<string>();
  for (const [, value] of body.matchAll(/(?:fill|stop-color)="(#[0-9a-fA-F]{3,6})"/g)) colors.add(longHex(value!));
  if (/fill="(?:black|currentColor)"/.test(body)) colors.add("#000000");
  for (const [shape] of body.matchAll(/<(?:path|circle|rect|ellipse|polygon)\b[^>]*>/g)) {
    if (!/\bfill=/.test(shape)) colors.add("#000000");
  }
  return [...colors].sort();
}

function longHex(hex: string): string {
  const h = hex.slice(1).toLowerCase();
  return `#${h.length === 3 ? [...h].map((c) => c + c).join("") : h}`;
}

function generate(): LogoDrawings & { comment: string } {
  const bySlug = new Map(
    Object.values(simpleIcons)
      .filter((icon): icon is simpleIcons.SimpleIcon => typeof icon === "object" && icon !== null && "slug" in icon)
      .map((icon) => [icon.slug, icon]),
  );
  const simple: Record<string, SimpleDrawing> = {};
  for (const [slug, title] of [...SIMPLE_LOGOS].sort(([a], [b]) => a.localeCompare(b))) {
    const icon = bySlug.get(slug);
    if (!icon) throw new Error(`No logo "${slug}" in simple-icons`);
    if (icon.title !== title) throw new Error(`simple-icons calls "${slug}" "${icon.title}", not "${title}"`);
    simple[slug] = { path: icon.path, color: `#${icon.hex.toLowerCase()}` };
  }

  const set = createRequire(import.meta.url)("@iconify-json/logos/icons.json") as IconSet;
  const color: Record<string, ColorDrawing> = {};
  for (const [key] of [...COLOR_LOGOS].sort(([a], [b]) => a.localeCompare(b))) {
    const icon = set.icons[key];
    if (!icon) throw new Error(`No logo "${key}" in @iconify-json/logos`);
    color[key] = {
      body: icon.body,
      width: icon.width ?? set.width ?? 16,
      height: icon.height ?? set.height ?? 16,
      colors: colorsOf(icon.body),
    };
  }
  return {
    comment:
      "Generated by frontend/src/registry/logoDrawings.test.ts from simple-icons and @iconify-json/logos (SVG Logos), both CC0. Do not edit.",
    simple,
    color,
  };
}

describe("logoDrawings.json", () => {
  it("holds exactly the drawings of SIMPLE_LOGOS and COLOR_LOGOS", () => {
    const text = JSON.stringify(generate(), null, 2) + "\n";
    if (process.env.UPDATE_LOGO_DRAWINGS) writeFileSync(FILE, text);
    expect(readFileSync(FILE, "utf8"), "run with UPDATE_LOGO_DRAWINGS=1 to regenerate").toBe(text);
  });

  it("lightens one-colour logos too dark for the box, and leaves the rest alone", () => {
    const { simple } = generate();
    for (const slug of ["express", "django", "apachekafka", "ios", "kong", "nginx", "redis", "docker"]) {
      const color = logoColor(simple[slug]!, BOX_BACKGROUND);
      expect(contrastRatio(color, BOX_BACKGROUND), `${slug} ${color}`).toBeGreaterThanOrEqual(3);
    }
    expect(logoColor(simple.redis!, BOX_BACKGROUND)).toBe("#ff4438");
  });

  it("puts dark full-colour logos on a light backing, and leaves colourful ones as they are", () => {
    const { color } = generate();
    expect(needsBacking(color["openai-icon"]!, BOX_BACKGROUND)).toBe(true); // black
    expect(needsBacking(color["aws-lambda"]!, BOX_BACKGROUND)).toBe(false); // orange tile, white glyph
    expect(needsBacking(color["microsoft-icon"]!, BOX_BACKGROUND)).toBe(false);
  });

  it("reads colours as SVG paints them", () => {
    expect(colorsOf('<path fill="#F90" d=""/><stop stop-color="#c8511b"/>')).toEqual(["#c8511b", "#ff9900"]);
    expect(colorsOf('<path d="M0 0"/>')).toEqual(["#000000"]);
  });
});
